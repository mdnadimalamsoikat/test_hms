/* Run As : SYS AS SYSDBA.  Age Windows e D:\HMS_BACKUP\dump folder banan */
CREATE OR REPLACE DIRECTORY HMS_BACKUP_DIR AS 'D:\HMS_BACKUP\dump';
GRANT READ, WRITE ON DIRECTORY HMS_BACKUP_DIR TO HMS_APP;
GRANT DATAPUMP_EXP_FULL_DATABASE, DATAPUMP_IMP_FULL_DATABASE TO HMS_APP;
-- Flashback table use korar jonno
GRANT FLASHBACK ANY TABLE TO HMS_APP;
SELECT DIRECTORY_NAME, DIRECTORY_PATH FROM DBA_DIRECTORIES WHERE DIRECTORY_NAME='HMS_BACKUP_DIR';
